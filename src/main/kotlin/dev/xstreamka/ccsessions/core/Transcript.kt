package dev.xstreamka.ccsessions.core

import com.google.gson.JsonObject
import java.time.Instant

/*
 * Формат транскриптов Claude Code — внутренний и меняется между версиями.
 * Поэтому парсер «терпимый»: неизвестные типы строк и блоков пропускаются,
 * отсутствующие поля не ломают разбор.
 */

data class Usage(
    val input: Long = 0,
    val output: Long = 0,
    val cacheRead: Long = 0,
    val cacheCreation: Long = 0,
) {
    /** Сколько токенов ушло в контекст запроса. */
    val context: Long get() = input + cacheRead + cacheCreation
    operator fun plus(o: Usage) = Usage(input + o.input, output + o.output, cacheRead + o.cacheRead, cacheCreation + o.cacheCreation)

    companion object {
        fun from(o: JsonObject?): Usage? {
            o ?: return null
            return Usage(
                input = o.long("input_tokens") ?: 0,
                output = o.long("output_tokens") ?: 0,
                cacheRead = o.long("cache_read_input_tokens") ?: 0,
                cacheCreation = o.long("cache_creation_input_tokens") ?: 0,
            )
        }
    }
}

sealed class TItem {
    abstract val ts: Instant?

    data class UserPrompt(override val ts: Instant?, val text: String, val images: Int = 0) : TItem()
    data class SlashCommand(override val ts: Instant?, val command: String, val args: String) : TItem()
    data class AssistantText(override val ts: Instant?, val text: String, val model: String?) : TItem()
    data class Thinking(override val ts: Instant?, val text: String) : TItem()
    data class ToolCall(
        override val ts: Instant?,
        val id: String,
        val name: String,
        val input: JsonObject,
        var result: ToolResult? = null,
    ) : TItem()

    data class Note(override val ts: Instant?, val kind: NoteKind, val title: String, val body: String = "") : TItem()
}

data class ToolResult(val text: String, val isError: Boolean, val structured: JsonObject?)

enum class NoteKind { COMPACT, COMMAND_OUTPUT, SHELL, INTERRUPT, SYSTEM, ERROR }

data class Transcript(
    val items: List<TItem>,
    val summary: SessionSummary,
)

/** Утилиты разбора отдельных строк, общие для индекса и просмотрщика. */
internal object Lines {
    private val commandName = Regex("<command-name>(.*?)</command-name>", RegexOption.DOT_MATCHES_ALL)
    private val commandArgs = Regex("<command-args>(.*?)</command-args>", RegexOption.DOT_MATCHES_ALL)
    private val wrapped = Regex("^\\s*<(local-command-stdout|local-command-stderr|bash-input|bash-stdout|bash-stderr)>(.*?)</\\1>", RegexOption.DOT_MATCHES_ALL)

    fun timestamp(o: JsonObject): Instant? {
        val s = o.str("timestamp") ?: return null
        return try {
            Instant.parse(s)
        } catch (_: Exception) {
            s.toLongOrNull()?.let { Instant.ofEpochMilli(it) }
        }
    }

    /** Текстовые блоки сообщения пользователя (без tool_result). null — если это не «промпт». */
    fun userText(msg: JsonObject?): Pair<String, Int>? {
        msg ?: return null
        val content = msg.get("content") ?: return null
        if (content.isJsonPrimitive) return content.asString to 0
        if (!content.isJsonArray) return null
        val sb = StringBuilder()
        var images = 0
        var hasToolResult = false
        for (b in content.asJsonArray) {
            if (!b.isJsonObject) continue
            val bo = b.asJsonObject
            when (bo.str("type")) {
                "text" -> {
                    if (sb.isNotEmpty()) sb.append("\n\n")
                    sb.append(bo.str("text") ?: "")
                }
                "image" -> images++
                "tool_result" -> hasToolResult = true
            }
        }
        if (hasToolResult && sb.isEmpty()) return null
        if (sb.isEmpty() && images == 0) return null
        return sb.toString() to images
    }

    sealed interface Classified
    data class Prompt(val text: String, val images: Int) : Classified
    data class Command(val name: String, val args: String) : Classified
    data class Wrapped(val tag: String, val body: String) : Classified
    data object Interrupt : Classified
    data object Skip : Classified

    fun classifyUserText(text: String, images: Int): Classified {
        val t = text.trim()
        if (t.startsWith("Caveat: The messages below were generated by the user")) return Skip
        commandName.find(t)?.let { m ->
            val args = commandArgs.find(t)?.groupValues?.get(1)?.trim().orEmpty()
            return Command(m.groupValues[1].trim(), args)
        }
        wrapped.find(t)?.let { m -> return Wrapped(m.groupValues[1], m.groupValues[2].trim()) }
        if (t.startsWith("[Request interrupted by user")) return Interrupt
        if (t.isEmpty() && images == 0) return Skip
        return Prompt(text, images)
    }
}

object TranscriptParser {

    fun parse(sessionId: String, lines: Sequence<String>, sizeBytes: Long = 0): Transcript {
        val items = ArrayList<TItem>()
        val calls = HashMap<String, TItem.ToolCall>()
        val acc = SessionAccumulator(sessionId)
        val seen = HashSet<String>()

        for (line in lines) {
            if (line.isBlank()) continue
            val o = parseObject(line) ?: continue
            acc.accept(o)
            val uuid = o.str("uuid")
            if (uuid != null && !seen.add(uuid)) continue
            if (o.bool("isSidechain") || o.bool("isMeta")) continue
            val ts = Lines.timestamp(o)
            when (o.str("type")) {
                "user" -> parseUser(o, ts, items, calls)
                "assistant" -> parseAssistant(o, ts, items, calls)
                "system" -> {
                    val content = o.str("content") ?: o.str("message")
                    val sub = o.str("subtype")
                    when {
                        sub == "compact_boundary" -> items += TItem.Note(ts, NoteKind.COMPACT, I18n.msg("note.compacted"))
                        !content.isNullOrBlank() -> {
                            val kind = if (o.str("level") == "error") NoteKind.ERROR else NoteKind.SYSTEM
                            items += TItem.Note(ts, kind, content.lineSequence().first().take(200), content)
                        }
                    }
                }
            }
        }
        return Transcript(items, acc.build(sizeBytes))
    }

    private fun parseUser(o: JsonObject, ts: Instant?, items: MutableList<TItem>, calls: Map<String, TItem.ToolCall>) {
        val msg = o.obj("message")
        if (o.bool("isCompactSummary")) {
            items += TItem.Note(ts, NoteKind.COMPACT, I18n.msg("note.compactSummary"), Lines.userText(msg)?.first.orEmpty())
            return
        }
        // tool_result → привязываем к вызову
        msg?.arr("content")?.forEach { b ->
            if (!b.isJsonObject) return@forEach
            val bo = b.asJsonObject
            if (bo.str("type") == "tool_result") {
                val id = bo.str("tool_use_id") ?: return@forEach
                val call = calls[id] ?: return@forEach
                call.result = ToolResult(
                    text = bo.get("content").flattenText(200_000),
                    isError = bo.bool("is_error"),
                    structured = o.obj("toolUseResult"),
                )
            }
        }
        val (text, images) = Lines.userText(msg) ?: return
        when (val c = Lines.classifyUserText(text, images)) {
            is Lines.Prompt -> items += TItem.UserPrompt(ts, c.text, c.images)
            is Lines.Command -> items += TItem.SlashCommand(ts, c.name, c.args)
            is Lines.Wrapped -> {
                val kind = if (c.tag.startsWith("bash")) NoteKind.SHELL else NoteKind.COMMAND_OUTPUT
                val title = when (c.tag) {
                    "bash-input" -> "$ " + c.body.lineSequence().first()
                    "bash-stdout", "bash-stderr" -> I18n.msg("note.shellOutput")
                    else -> I18n.msg("note.commandOutput")
                }
                if (c.body.isNotBlank() || c.tag == "bash-input") items += TItem.Note(ts, kind, title, if (c.tag == "bash-input") "" else c.body)
            }
            Lines.Interrupt -> items += TItem.Note(ts, NoteKind.INTERRUPT, I18n.msg("note.interrupted"))
            Lines.Skip -> {}
        }
    }

    private fun parseAssistant(o: JsonObject, ts: Instant?, items: MutableList<TItem>, calls: MutableMap<String, TItem.ToolCall>) {
        val msg = o.obj("message") ?: return
        val model = msg.str("model")
        if (o.bool("isApiErrorMessage")) {
            val text = msg.get("content").flattenText(2000)
            items += TItem.Note(ts, NoteKind.ERROR, I18n.msg("note.apiError"), text)
            return
        }
        val content = msg.get("content") ?: return
        if (content.isJsonPrimitive) {
            items += TItem.AssistantText(ts, content.asString, model)
            return
        }
        if (!content.isJsonArray) return
        for (b in content.asJsonArray) {
            if (!b.isJsonObject) continue
            val bo = b.asJsonObject
            when (bo.str("type")) {
                "text" -> bo.str("text")?.takeIf { it.isNotBlank() }?.let { items += TItem.AssistantText(ts, it, model) }
                "thinking" -> bo.str("thinking")?.takeIf { it.isNotBlank() }?.let { items += TItem.Thinking(ts, it) }
                "tool_use", "server_tool_use" -> {
                    val id = bo.str("id") ?: continue
                    val call = TItem.ToolCall(ts, id, bo.str("name") ?: "tool", bo.obj("input") ?: JsonObject())
                    calls[id] = call
                    items += call
                }
            }
        }
    }
}
